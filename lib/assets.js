'use strict';

/**
 * 静态资源的处理：HTML 与 CSS 压缩、图标拷贝。
 */

const fs = require('fs-extra');
const CleanCSS = require('clean-css');
// html-minifier 已停止维护，改用其 terser 分支
const { minify: minifyWithOptions } = require('html-minifier-terser');

const HTML_MINIFY_OPTIONS = {
    collapseWhitespace: true,
    includeAutoGeneratedTags: true,
    removeAttributeQuotes: true,
    removeComments: true,
    removeRedundantAttributes: true,
    removeScriptTypeAttributes: true,
    removeStyleLinkTypeAttributes: true,
    sortClassName: true,
    useShortDoctype: true,
};

const CSS_MINIFY_OPTIONS = {
    level: 2,
};

/**
 * 压缩 HTML
 * @param {string} html
 * @returns {Promise<string>}
 */
function minifyHtml(html) {
    return minifyWithOptions(html, HTML_MINIFY_OPTIONS);
}

/**
 * 压缩并写出样式文件
 * @param {{ source: string, target: string }} paths
 * @returns {Promise<{ sourceBytes: number, outputBytes: number }>}
 */
async function writeStylesheet({ source, target }) {
    const css = await fs.readFile(source, 'utf8');
    const result = new CleanCSS(CSS_MINIFY_OPTIONS).minify(css);

    if (result.errors.length > 0) {
        throw new Error(`CSS 压缩失败：\n${result.errors.join('\n')}`);
    }

    await fs.outputFile(target, result.styles);
    return {
        sourceBytes: Buffer.byteLength(css),
        outputBytes: Buffer.byteLength(result.styles),
    };
}

/**
 * 拷贝站点图标
 * @param {{ source: string, target: string }} paths
 * @returns {Promise<number>} 拷贝的文件数量
 */
async function copyIcons({ source, target }) {
    await fs.emptyDir(target);
    await fs.copy(source, target);
    const files = await fs.readdir(target);
    return files.length;
}

module.exports = { minifyHtml, writeStylesheet, copyIcons };
